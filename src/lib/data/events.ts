function buildEvent(seed: EventSeed): BeautyEvent {
  const h = hashString(seed.id);
  return {
    id: seed.id,
    slug: seed.slug,
    title: seed.title,
    type: seed.type,
    summary: seed.summary,
    description: seed.description,
    categories: seed.cats,
    cityId: seed.city,
    venue: seed.venue,
    startDate: seed.start,
    endDate: seed.end,
    hostName: seed.host,
    hostBrandId: seed.brand,
    price: seed.price,
    capacity: seed.capacity,
    attending: Math.round(seed.capacity * (0.35 + ((h % 55) / 100))),
    online: seed.online,
    languages: seed.langs,
    coverSeed: seed.id,
    speakerUserIds: seed.speakers,
  };
}

export const EVENTS: BeautyEvent[] = SEEDS.map(buildEvent);
export const EVENT_BY_ID = new Map(EVENTS.map((e) => [e.id, e]));
