function buildPerson(seed: PersonSeed, index: number): PersonView {
  const h = hashString(seed.id);
  const scale = seed.exp === "expert" ? 24 : seed.exp === "established" ? 12 : seed.exp === "emerging" ? 6 : 2;
  return {
    id: seed.id,
    handle: seed.handle,
    name: seed.name,
    avatarSeed: seed.id,
    createdAt: new Date(Date.UTC(2023, index % 12, (h % 27) + 1)).toISOString(),
    verified: Boolean(seed.verified),
    profile: {
      userId: seed.id,
      headline: seed.headline,
      bio: seed.bio,
      role: seed.role,
      secondaryRoles: seed.also ?? [],
      categories: seed.cats,
      skillIds: seed.skills,
      interestIds: seed.interests,
      languages: seed.langs,
      countryId: seed.country,
      cityId: seed.city,
      experience: seed.exp,
      yearsActive: seed.years,
      availability: seed.avail,
      openTo: seed.openTo,
      goals: seed.goals,
      targetCityIds: seed.targets,
      followers: 400 + (h % 900) * scale,
      following: 120 + (h % 400),
      connections: 40 + (h % 260) + scale * 6,
      achievements: (seed.awards ?? []).map(([label, year, issuer], i) => ({
        id: `${seed.id}-ach-${i}`,
        label,
        year,
        issuer,
      })),
    },
  };
}

export const PEOPLE: PersonView[] = SEEDS.map(buildPerson);

export const PERSON_BY_ID = new Map(PEOPLE.map((p) => [p.id, p]));

