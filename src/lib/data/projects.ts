function buildProject(seed: ProjectSeed): Project {
  const h = hashString(seed.id);
  return {
    id: seed.id,
    code: seed.code,
    title: seed.title,
    type: seed.type,
    status: seed.status,
    summary: seed.summary,
    overview: seed.overview,
    categories: seed.cats,
    cityIds: seed.cities,
    ownerUserId: seed.owner,
    brandIds: seed.brands,
    startDate: seed.start,
    endDate: seed.end,
    timeline: seed.phases.map(([label, period, status], i) => ({
      id: `${seed.id}-ph${i}`,
      label,
      period,
      status,
    })),
    memberIds: seed.members,
    capacity: seed.capacity,
    roleSlots: seed.slots.map(([role, count, filled, skillIds]) => ({ role, count, filled, skillIds })),
    requiredSkillIds: Array.from(new Set(seed.slots.flatMap(([, , , skills]) => skills))),
    budget: seed.budget,
    languages: seed.langs,
    remoteFriendly: seed.remote,
    coverSeed: seed.id,
    createdAt: new Date(Date.UTC(2026, (h % 8) + 1, (h % 26) + 1)).toISOString(),
    applicationsCount: 8 + (h % 140),
  };
}

export const PROJECTS: Project[] = SEEDS.map(buildProject);
