function buildBrand(seed: BrandSeed): Brand {
  const h = hashString(seed.id);
  return {
    id: seed.id,
    slug: seed.slug,
    name: seed.name,
    type: seed.type,
    tagline: seed.tagline,
    story: seed.story,
    categories: seed.cats,
    countryId: seed.country,
    cityId: seed.city,
    marketCityIds: seed.markets,
    founded: seed.founded,
    teamSize: seed.team,
    avatarSeed: seed.id,
    verified: Boolean(seed.verified),
    followers: 900 + (h % 60_000),
    languages: seed.langs,
    lookingFor: seed.lookingFor,
    values: seed.values,
    memberUserIds: seed.members,
    products: seed.products.map(([name, category, description, price], i) => ({
      id: `${seed.id}-p${i}`,
      brandId: seed.id,
      name,
      category,
      description,
      price,
    })),
    openOpportunities: seed.opportunities.map(
      ([title, type, roles, cityId, remote, compensation, deadline, description], i) => ({
        id: `${seed.id}-o${i}`,
        brandId: seed.id,
        title,
        type,
        roles,
        cityId,
        remote,
        compensation,
        deadline,
        description,
      }),
    ),
  };
}

export const BRANDS: Brand[] = SEEDS.map(buildBrand);
export const BRAND_BY_ID = new Map(BRANDS.map((b) => [b.id, b]));
export const OPPORTUNITIES = BRANDS.flatMap((b) => b.openOpportunities);
