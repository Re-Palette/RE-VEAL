/**
 * Pre-computes the world map SVG geometry used by <WorldMap />.
 *
 * We project once, at build time, with a plain equirectangular projection so the
 * runtime needs no geo libraries and so lat/lng -> x/y stays a two-line formula
 * (see src/lib/geo/projection.ts). Re-run with `npm run generate:map`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));

const WIDTH = 1000;
const HEIGHT = WIDTH / 2;

const projection = geoEquirectangular()
  .scale(WIDTH / (2 * Math.PI))
  .translate([WIDTH / 2, HEIGHT / 2]);

const path = geoPath(projection).digits(1);
const countries = feature(topo, topo.objects.countries).features;

const shapes = countries
  .map((f) => ({ id: String(f.id), name: String(f.properties?.name ?? ""), d: path(f) ?? "" }))
  .filter((c) => c.d.length > 0 && c.name !== "Antarctica")
  .sort((a, b) => a.name.localeCompare(b.name));

const body = shapes.map((c) => `  { id: "${c.id}", name: ${JSON.stringify(c.name)}, d: "${c.d}" },`).join("\n");

mkdirSync("src/lib/geo", { recursive: true });
writeFileSync(
  "src/lib/geo/world-shapes.ts",
  `// AUTO-GENERATED by scripts/generate-world-map.mjs — do not edit by hand.
// Source: world-atlas (Natural Earth 110m), equirectangular, ${WIDTH}x${HEIGHT}.

export interface CountryShape {
  id: string;
  name: string;
  d: string;
}

export const WORLD_SHAPES: CountryShape[] = [
${body}
];
`,
);

console.log(`generated ${shapes.length} country shapes`);
